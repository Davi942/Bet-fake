import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:net';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const composeFile = join(root, 'compose.yaml');
const project = `bet-fake-test-${randomUUID().replaceAll('-', '')}`;

async function availablePort() {
  const server = createServer();
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const port = server.address().port;
  await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()));
  return port;
}

const port = await availablePort();
const environment = {
  ...process.env,
  COMPOSE_PROJECT_NAME: project,
  APP_PORT: String(port),
  POSTGRES_DB: 'bet_fake_test',
  POSTGRES_USER: 'bet_fake_test',
  POSTGRES_PASSWORD: randomUUID(),
  DEMO_ADMIN_PASSWORD: 'AdminDemo123!',
  DEMO_BETTOR_PASSWORD: 'ApostadorDemo123!',
  TEST_BASE_URL: `http://127.0.0.1:${port}`,
};
const requestedTests = process.argv.slice(2).filter(argument => argument.endsWith('.test.mjs'));
const testOptions = process.argv.slice(2).filter(argument => !argument.endsWith('.test.mjs'));
let running;
let interrupted = false;
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.once(signal, () => {
    interrupted = true;
    running?.kill(signal);
  });
}

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: root, env: environment, stdio: 'inherit' });
    running = child;
    child.once('error', reject);
    child.once('close', (code, signal) => {
      if (running === child) running = undefined;
      if (code === 0) resolve();
      else reject(new Error(`${command} terminou com ${signal ?? code}.`));
    });
  });
}

const compose = (...args) => run('docker', ['compose', '--file', composeFile, '--project-name', project, ...args]);
console.log(`Testes isolados: ${project} em ${environment.TEST_BASE_URL}`);
try {
  await compose('up', '--build', '--wait', '--wait-timeout', '180');
  if (interrupted) throw new Error('Testes interrompidos.');
  await run(process.execPath, ['--test', '--test-concurrency=1', ...testOptions, ...(requestedTests.length ? requestedTests : ['test/*.test.mjs'])]);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
  try { await compose('logs', '--no-color', '--tail', '100', 'app', 'db'); }
  catch (diagnosticError) { console.error(`Não foi possível coletar logs: ${diagnosticError.message}`); }
} finally {
  // This exact namespace was generated by this process; never clean the demo project.
  try { await compose('down', '--volumes', '--remove-orphans'); }
  catch (error) { console.error(`Falha ao limpar ${project}: ${error.message}`); process.exitCode = 1; }
}
